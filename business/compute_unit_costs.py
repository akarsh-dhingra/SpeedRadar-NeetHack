"""Paid-equivalent cost per run, computed from real runs' measured tokens.

Development ran on FREE tiers (actual spend $0). Paying customers cannot rely on free
quotas, so cost = measured tokens per model × the published paid price of the same model.
Only evidence runs (LLM cache off, accounting fix 8747783 or later) are used.
Run: uv run python business/compute_unit_costs.py <run_id> [<run_id> ...]
"""

import json
import statistics
import sys
from pathlib import Path

# USD per 1M tokens (input, output incl. thinking). Checked 2026-10-10.
PRICES = {
    # https://ai.google.dev/gemini-api/docs/pricing (paid tier, standard)
    "gemini-2.5-flash": (0.30, 2.50),
    "gemini-3.6-flash": (0.75, 3.75),   # rises to 1.50 / 7.50 on 2027-01-01
    "gemini-3.8-flash": (0.75, 3.75),   # rises to 1.50 / 7.50 on 2027-01-01
    "gemini-3.5-flash-lite": (0.30, 2.50),
    "gemini-3.1-flash-lite": (0.25, 1.50),
    # Gemma 4 is free-only on the Gemini API (no paid price listed). PROXY: OpenRouter's paid
    # price for the same model, https://openrouter.ai/api/v1/models (google/gemma-4-31b-it).
    "gemma-4-31b-it": (0.09, 0.34),
    # https://openrouter.ai/api/v1/models, the paid (non-:free) variant of the same model
    "nvidia/nemotron-3-super-120b-a12b:free": (0.08, 0.45),
    "google/gemma-4-31b-it:free": (0.09, 0.34),
}
CRUSTDATA_LIST = {"enrich_per_company": 2.0, "job_search_per_result": 0.03}  # credits, GET /account/endpoints


def run_cost(run_id: str) -> dict:
    s = json.loads(Path(f"runs/{run_id}/state.json").read_text())
    if "evidence" not in s["tags"]:
        raise SystemExit(f"{run_id} is not an evidence run (LLM cache was on)")
    usd, per_model, unpriced = 0.0, {}, []
    for model, u in s["llm_usage"].items():
        if model not in PRICES:
            unpriced.append(model)
            continue
        pin, pout = PRICES[model]
        c = u["tokens_in"] / 1e6 * pin + u["tokens_out"] / 1e6 * pout
        per_model[model] = {"calls": u["calls"], "tokens_in": u["tokens_in"], "tokens_out": u["tokens_out"],
                            "usd": round(c, 5)}
        usd += c
    samples = s["title_classes"].get("_samples", {})
    n_comp = len(s["competitors"])
    job_results = sum(len(v.get(k, [])) for v in samples.values() for k in ("job_search", "engineering_2y"))
    cold_credits = n_comp * CRUSTDATA_LIST["enrich_per_company"] + job_results * CRUSTDATA_LIST["job_search_per_result"]
    return {"run_id": run_id, "trace_ids": s.get("trace_ids") or [s["trace_id"]], "llm_usd": round(usd, 5),
            "per_model": per_model, "unpriced_models": unpriced,
            "llm_calls": sum(u["calls"] for u in s["llm_usage"].values()),
            "tokens_in": sum(u["tokens_in"] for u in s["llm_usage"].values()),
            "tokens_out": sum(u["tokens_out"] for u in s["llm_usage"].values()),
            "crustdata_credits_this_run": round(s["crustdata_credits"], 2),
            "crustdata_credits_cold": round(cold_credits, 2), "competitors": n_comp, "job_results": job_results}


def main(run_ids: list[str]) -> None:
    rows = [run_cost(r) for r in run_ids]
    mean = statistics.mean
    out = ["# Unit costs per run (paid-equivalent estimate)", "",
           "Generated by `business/compute_unit_costs.py` from evidence runs (LLM cache off). Development spend was "
           "**$0** (free tiers). These are the costs a paying deployment would face: **measured tokens × published "
           "paid price of the same model**, checked 2026-10-10. Price sources are in the script.", "",
           f"Runs: {len(rows)} (target 5; more are added as free-tier quota allows).", "",
           "| Run | Traces | LLM calls | Tokens in / out | Paid-equivalent LLM $ | Crustdata credits (this run / cold) |",
           "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['run_id']} | {', '.join('`' + t[:12] + '…`' for t in r['trace_ids'])} | {r['llm_calls']} | "
                   f"{r['tokens_in']:,} / {r['tokens_out']:,} | ${r['llm_usd']:.4f} | "
                   f"{r['crustdata_credits_this_run']} / {r['crustdata_credits_cold']} |")
    out += ["", f"**Mean paid-equivalent LLM cost per run: ${mean(r['llm_usd'] for r in rows):.4f}** (n={len(rows)})",
            f"**Mean Crustdata credits per cold run (no cache): {mean(r['crustdata_credits_cold'] for r in rows):.2f}** "
            f"= {rows[0]['competitors']} competitors × 2 credits + job results × 0.03.",
            "", "Crustdata does not publish a USD price per credit (docs: credits are bought in the dashboard). "
            "**Input needed:** USD per credit from https://app.crustdata.com/billing/credits.", ""]
    if any(r["unpriced_models"] for r in rows):
        out.append(f"Unpriced models (excluded): {sorted({m for r in rows for m in r['unpriced_models']})}")
    out += ["", "Per model (first run):", "", "| Model | Calls | Tokens in | Tokens out | $ |", "|---|---|---|---|---|"]
    for m, u in rows[0]["per_model"].items():
        out.append(f"| {m} | {u['calls']} | {u['tokens_in']:,} | {u['tokens_out']:,} | ${u['usd']:.5f} |")
    Path("business/unit_costs.md").write_text("\n".join(out) + "\n")
    Path("business/unit_costs.json").write_text(json.dumps(rows, indent=1))
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1:])
